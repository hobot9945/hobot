<#
.SYNOPSIS
    Универсальный скрипт проверки формальной структуры Markdown-таблиц для файлов primary.md и dt_fields.md.

.DESCRIPTION
    Скрипт построен на базе конечного автомата (State Machine) построчного разбора.
    Он проверяет следующие жесткие правила форматирования:
    1. Наличие пустой строки перед началом таблицы (требование парсеров Markdown).
    2. Целостность структуры таблицы: Заголовок -> Разделитель -> Тело данных.
    3. Отсутствие пустых строк внутри активной таблицы (до ее логического завершения).
    4. Строгая, непрерывная нумерация строк данных (01, 02, 03...).
    5. Соответствие фактического числа обработанных строк маркерам аудита (_audit: N или _item_audit: N).
Параметры
---------
-FilePath: путевое имя файла (путь абсолютный или относительный, от папки исполнения)
#>

param(
    [Parameter(Mandatory=$true)]
    [string]$FilePath
)

# Системная настройка: при любой непредвиденной ошибке (нет файла, нет доступа) сразу падаем (Fail-Fast).
$ErrorActionPreference = 'Stop'

# Ожидаемое минимальное количество колонок в таблицах данных (num | field | value | status | description | note)
$EXPECTED_COLUMNS = 6

if (-not (Test-Path -LiteralPath $FilePath)) {
    Write-Output "ОШИБКА: Файл не найден: $FilePath"
    exit 1
}

# -------------------------------------------------------------------------
# ИНИЦИАЛИЗАЦИЯ
# -------------------------------------------------------------------------

# Сборщик ошибок. Хранит все найденные проблемы, чтобы выдать единый отчет в конце,
# а не прерывать проверку на первой же опечатке.
$Errors = New-Object System.Collections.Generic.List[string]

# Вспомогательная функция для добавления ошибки в коллектор с указанием номера строки.
function Add-Error([int]$ln, [string]$msg) { $Errors.Add("Строка ${ln}: ${msg}") | Out-Null }

# Парсер строки таблицы: разбивает строку на массив ячеек
function Split-Row([string]$row) {
    $r = $row.Trim()
    if (-not $r.StartsWith("|")) { return @() }
    $parts = $r.Split("|")
    $cells = @()
    # Пропускаем пустоты до первой и после последней "|"
    for ($idx = 1; $idx -lt $parts.Length - 1; $idx++) { $cells += $parts[$idx].Trim() }
    return $cells
}

# --- Состояния конечного автомата (State Machine) ---
# Автомат отслеживает жизненный цикл одной Markdown-таблицы.
# Допустимые состояния:
# "OutOfTable"    - Мы находимся в обычном тексте (заголовки, списки, абзацы). Таблицы нет.
# "HeaderSeen"    - Мы только что прочитали заголовок таблицы (| num | field | ...).
# "SeparatorSeen" - Мы прочитали разделитель колонок (|---|---|).
# "InBody"        - Мы находимся внутри тела таблицы и читаем строки с реальными данными.
$State = "OutOfTable"

# --- Управляющие флаги и счетчики ---
# $blockRowCount: считает количество успешно прочитанных строк данных. 
# Сбрасывается в 0 после того, как встречен и проверен маркер _audit / _item_audit.
$blockRowCount = 0

# $expectedNum: ожидаемый номер для следующей строки данных (колонка num). Всегда начинается с 1.
$expectedNum = 1

# $inAuditBlock: флаг, показывающий, что мы начали копить строки данных, и теперь 
# скрипт ОБЯЗАН в будущем встретить маркер _audit или _item_audit для их сверки.
$inAuditBlock = $false

# $prevLineBlank: помнит, была ли предыдущая строка пустой. 
# На старте считаем, что "до начала файла" была пустота (true).
$prevLineBlank = $true

# Загружаем всё содержимое файла в память (в массив строк) с учетом кодировки UTF-8.
$lines = Get-Content -LiteralPath $FilePath -Encoding UTF8

# -------------------------------------------------------------------------
# ОСНОВНОЙ ЦИКЛ ПАРСИНГА ФАЙЛА
# -------------------------------------------------------------------------

for ($i = 0; $i -lt $lines.Count; $i++) {
    $lnNo = $i + 1
    $line = $lines[$i]
    $trimmed = $line.Trim()

    # --- 1. Определение семантики (типа) текущей строки ---

    # Проверка на полностью пустую строку или строку, состоящую только из пробелов/табов.
    $isBlank = [string]::IsNullOrWhiteSpace($line)

    # Базовый признак любой строки таблицы в Markdown: она начинается с вертикальной черты.
    $isTableLike = $trimmed.StartsWith("|")

    # Проверка на разделитель (Separator). 
    # Ищем начало с "|", затем разрешены только пробелы, тире, двоеточия (для выравнивания) и разделители "|".
    # Обязательно наличие хотя бы одного тире, чтобы не спутать с пустой табличной строкой "|||".
    $isSeparator = $isTableLike -and ($trimmed -match '^\|[\s\-:\|]*\|$') -and ($trimmed -match '-')

    # Проверка на строку данных (Data Row). 
    # Шаблон: начинается с "|", затем возможны пробелы, затем ровно ДВЕ цифры, возможны пробелы, затем "|".
    $isDataRow = $isTableLike -and ($trimmed -match '^\|\s*(\d{2})\s*\|')

    # Проверка на маркер аудита (_audit: N или _item_audit: N).
    # Допускает пробелы вокруг, допускает лидирующий дефис, захватывает само число во вторую группу $matches[2].
    $isAuditMarker = $trimmed -match '^\s*(?:-\s*)?_(item_)?audit\s*:\s*(\d+)\s*$'

    # --- 2. Логика переходов конечного автомата ---

    if ($State -eq "OutOfTable") {
        # СОСТОЯНИЕ: Вне таблицы
        if ($isTableLike) {
            # МЫ НАШЛИ НАЧАЛО ТАБЛИЦЫ.

            # Правило: Перед первой строкой таблицы (заголовком) обязательно должна быть пустая строка.
            if (-not $prevLineBlank) {
                Add-Error $lnNo "Отсутствует пустая строка перед началом таблицы."
            }

            # Анализируем, с чего именно началась таблица:
            if ($isDataRow) {
                Add-Error $lnNo "Таблица началась сразу со строки данных (пропущен заголовок)."
                $State = "InBody"
                $inAuditBlock = $true
            } elseif ($isSeparator) {
                Add-Error $lnNo "Таблица началась с разделителя (пропущен заголовок)."
                $State = "SeparatorSeen"
            } else {
                # Идеальный сценарий: началась обычная строка с "|", которая не является ни данными, ни разделителем.
                # Значит, это заголовок таблицы.
                $State = "HeaderSeen"
            }
        }

    } elseif ($State -eq "HeaderSeen") {
        # СОСТОЯНИЕ: Прочитан заголовок таблицы
        if ($isBlank) {
            # Правило: Внутри таблицы не может быть пустых строк.
            Add-Error $lnNo "Встречена пустая строка сразу после заголовка таблицы (таблица разорвана)."
            $State = "OutOfTable"
        } elseif ($isSeparator) {
            # Нормальный ход вещей: после заголовка идет разделитель.
            $State = "SeparatorSeen"
        } else {
            Add-Error $lnNo "После заголовка таблицы ожидался разделитель (|---|), но найдена другая строка."
            # Пытаемся восстановить логику, если автор случайно сразу начал писать данные:
            if ($isDataRow) {
                $State = "InBody"
                $inAuditBlock = $true
            }
        }

    } elseif ($State -eq "SeparatorSeen") {
        # СОСТОЯНИЕ: Прочитан разделитель
        if ($isBlank) {
            Add-Error $lnNo "Встречена пустая строка после разделителя (пустая таблица без данных)."
            $State = "OutOfTable"
        } elseif ($isTableLike) {
            # Любая табличная строка после разделителя считается началом тела таблицы.
            $State = "InBody"
            $inAuditBlock = $true
        }

    } elseif ($State -eq "InBody") {
        # СОСТОЯНИЕ: Чтение тела таблицы (данных)
        if ($isBlank) {
            # Нормальное завершение таблицы Markdown — пустая строка.
            $State = "OutOfTable"
        } elseif (-not $isTableLike) {
            # Если строка не пустая, но и не начинается с "|", значит начался обычный текст. Таблица тоже закрывается.
            $State = "OutOfTable"
        }
        # Если строка $isTableLike - остаемся в состоянии InBody и продолжаем считывать данные.
    }


    # --- 3. Валидация данных и инкремент счетчиков ---

    # Если строка идентифицирована как строка данных (даже если автомат в сбое, мы проверяем её номер)
    if ($isDataRow) {

        # 1. Проверка количества колонок
        $cells = Split-Row $trimmed
        if ($cells.Count -ne $EXPECTED_COLUMNS) {
            Add-Error $lnNo ("Нарушено число колонок в таблице данных. Ожидалось $EXPECTED_COLUMNS, получено $($cells.Count).")
        }

        # 2. Извлекаем номер из первой колонки.
        $null = $trimmed -match '^\|\s*(\d{2})\s*\|'
        $actualNum = [int]$matches[1]

        # Правило: Номера должны идти строго по порядку: 01, 02, 03...
        if ($actualNum -ne $expectedNum) {
            Add-Error $lnNo ("Нарушена последовательность num. Ожидалось {0:00}, получено {1:00}." -f $expectedNum, $actualNum)
        }

        # 3. Готовимся к следующей строке: увеличиваем ожидаемый номер на 1.
        $expectedNum = $actualNum + 1

        # 4. Фиксируем, что мы успешно прочитали еще одну строку данных текущего блока.
        $blockRowCount++
    }

    # --- 4. Проверка аудита (закрытие логического блока) ---

    if ($isAuditMarker) {
        # Вытаскиваем число из маркера _audit: N
        $expectedAudit = [int]$matches[2]

        if (-not $inAuditBlock -and $expectedAudit -ne 0) {
            # Если мы не накопили ни одной строки данных, но маркер требует проверку N > 0.
            Add-Error $lnNo "Маркер аудита ($expectedAudit) найден вне блока данных (или данные перед ним отсутствуют)."
        } else {
            # Основная сверка: число прочитанных строк данных должно совпасть с числом в маркере.
            if ($blockRowCount -ne $expectedAudit) {
                Add-Error $lnNo ("Несоответствие аудита. В маркере указано: $expectedAudit, фактически прочитано строк данных: $blockRowCount.")
            }
        }

        # Жесткий сброс переменных аудита. 
        # Блок закрыт, мы готовы собирать данные для следующего документа/массива.
        $inAuditBlock = $false
        $blockRowCount = 0
        $expectedNum = 1
    }

    # Сохраняем состояние текущей строки для проверки правила "пустая строка перед таблицей" на следующей итерации.
    $prevLineBlank = $isBlank
}

# -------------------------------------------------------------------------
# ФИНАЛЬНЫЕ ПРОВЕРКИ
# -------------------------------------------------------------------------

# Если мы дошли до конца файла, но так и не встретили закрывающий маркер _audit для накопленных данных:
if ($inAuditBlock) {
    Add-Error $lines.Count "Конец файла достигнут, но блок данных не был закрыт маркером _audit / _item_audit."
}

# -------------------------------------------------------------------------
# ВЫВОД ОТЧЕТА И ЗАВЕРШЕНИЕ РАБОТЫ
# -------------------------------------------------------------------------

Write-Output "Файл: $FilePath"

if ($Errors.Count -gt 0) {
    Write-Output "НАЙДЕНЫ ОШИБКИ ($($Errors.Count)):"
    # Выводим каждую ошибку с отступом для удобства чтения
    $Errors | ForEach-Object { Write-Output "  $_" }
    exit 1
} else {
    Write-Output "OK"
    exit 0
}